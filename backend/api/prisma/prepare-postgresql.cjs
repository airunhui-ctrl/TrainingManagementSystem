const { mkdirSync, readFileSync, writeFileSync } = require('node:fs')
const { resolve } = require('node:path')
const { spawnSync } = require('node:child_process')

const cwd = resolve(__dirname, '..')
const databaseUrl = String(process.env.DATABASE_URL || '').trim()
if (!/^postgres(ql)?:\/\//i.test(databaseUrl)) throw new Error('准备 PostgreSQL 前必须设置 DATABASE_URL=postgresql://...；当前 SQLite 不会被修改')

const sourceSchema = readFileSync(resolve(__dirname, 'schema.prisma'), 'utf8')
const postgresDir = resolve(__dirname, 'postgresql')
const schemaPath = resolve(postgresDir, 'schema.prisma')
const migrationDir = resolve(postgresDir, 'migrations', '0001_init')
mkdirSync(migrationDir, { recursive: true })
writeFileSync(schemaPath, sourceSchema.replace('provider = "sqlite"', 'provider = "postgresql"'), 'utf8')
writeFileSync(resolve(postgresDir, 'migrations', 'migration_lock.toml'), '# Generated by prepare-postgresql.cjs\nprovider = "postgresql"\n', 'utf8')

const pnpm = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm'
const run = (args) => {
  const result = spawnSync(pnpm, args, { cwd, env: { ...process.env, DATABASE_URL: databaseUrl }, encoding: 'utf8' })
  if (result.status !== 0) {
    process.stderr.write(result.stdout || '')
    process.stderr.write(result.stderr || '')
    throw new Error(`命令失败：${pnpm} ${args.join(' ')}`)
  }
  return result.stdout || ''
}

run(['exec', 'prisma', 'generate', '--schema', schemaPath])
const sql = run(['exec', 'prisma', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', schemaPath, '--script'])
if (!sql.trim()) throw new Error('Prisma 没有生成 PostgreSQL migration SQL')
writeFileSync(resolve(migrationDir, 'migration.sql'), sql, 'utf8')
console.log(JSON.stringify({ schemaPath, migrationPath: resolve(migrationDir, 'migration.sql'), provider: 'postgresql' }, null, 2))
